import assert from 'node:assert/strict';
import {validateCounts,uniqueSexPartners,partnerScenario,hivScenario,percent} from '../dist/model.mjs';
const base={kissed:0,protectedPartners:0,unprotectedPartners:1,overlap:0};
const opts={route:'vaginal_insertive',q:1,protectedActs:1,unprotectedActs:1};
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-12,`${a} != ${b}`);
close(hivScenario(base,opts).risk,0.0004);
close(hivScenario({...base,protectedPartners:1,unprotectedPartners:0},opts).risk,0.00008);
close(hivScenario({...base,unprotectedPartners:10},opts).risk,1-(1-.0004)**10);
// Infection status is shared within a partner; do not draw it again each act.
close(hivScenario(base,{...opts,q:.1,unprotectedActs:10}).risk,.1*(1-(1-.0004)**10));
close(hivScenario({...base,protectedPartners:1,overlap:1},{...opts,q:.1}).risk,.1*(1-(1-.0004)*(1-.00008)));
assert.equal(uniqueSexPartners({...base,protectedPartners:1,overlap:1}),1);
const allProtected={...base,protectedPartners:20,unprotectedPartners:0};
const mixed=hivScenario({...allProtected,unprotectedPartners:10,overlap:5},{...opts,q:.002,protectedActs:3,unprotectedActs:4});
assert.ok(mixed.risk>0&&mixed.risk<mixed.baseline);
close(hivScenario(base,{...opts,q:0}).risk,0);
close(hivScenario({...base,unprotectedPartners:0},opts).risk,0);
assert.equal(hivScenario(base,{...opts,route:'oral'}),null);
assert.ok(validateCounts({...base,overlap:2}));
assert.ok(validateCounts({...base,kissed:-1}));
assert.ok(validateCounts({...base,kissed:.5}));
assert.ok(validateCounts({...base,kissed:NaN}));
assert.throws(()=>hivScenario(base,{...opts,q:2}),RangeError);
assert.throws(()=>hivScenario(base,{...opts,protectedActs:0}),RangeError);
close(partnerScenario(.64,2),.8704);
close(partnerScenario(.13,0),0);
close(partnerScenario(1,2),1);
assert.equal(percent(.99999),'>99.9%');
assert.equal(percent(.995),'99.5%');
assert.equal(percent(1),'>99.9%');
assert.equal(percent(.00000001),'<0.0001%');
console.log('Model checks passed: reference rates, repeated partners, overlap, protection, boundaries, validation, formatting.');
